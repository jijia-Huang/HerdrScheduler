// `hsched install`: generate the herdr plugin manifest with absolute paths, optionally link it,
// write the hsched.cmd launcher and install.json (how the cached Claude plugin finds this folder).
import { mkdirSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { homedir } from 'node:os'
import { TOOL_ROOT, home } from './paths.mjs'
import { writeJson } from './store.mjs'
import { herdr } from './herdr.mjs'

const tomlStr = s => `'${s}'` // TOML literal string: no escapes, fine for Windows paths without '

export function manifest({ id, node, homeDir }) {
  const script = name => join(TOOL_ROOT, 'plugin', name)
  const tail = [...(homeDir ? ['--home', homeDir] : []), '--plugin-id', id]
  const cmd = (name, ...extra) => `[${[node, script(name), ...extra, ...tail].map(tomlStr).join(', ')}]`
  return `# Generated by \`hsched install\` — do not edit by hand; run it again instead.
id = "${id}"
name = "HerdrScheduler${id === 'herdr-scheduler' ? '' : ` (${id})`}"
version = "0.1.0"
min_herdr_version = "0.8.0"
platforms = ["windows"]

[[startup]]
command = ${cmd('startup.mjs')}

[[events]]
on = "pane.closed"
command = ${cmd('watchdog.mjs')}

[[events]]
on = "pane.agent_status_changed"
command = ${cmd('watchdog.mjs')}

[[panes]]
id = "scheduler"
title = "排程器"
placement = "tab"
command = ${cmd('scheduler-pane.mjs')}

[[actions]]
id = "open"
title = "HerdrScheduler: 打開排程器"
contexts = ["workspace"]
command = ${cmd('action.mjs', 'open')}

[[actions]]
id = "tick-now"
title = "HerdrScheduler: 立刻檢查一次"
contexts = ["workspace"]
command = ${cmd('action.mjs', 'tick-now')}
`
}

export async function install(opt = {}) {
  const id = opt.id ?? 'herdr-scheduler'
  const homeDir = opt.home ?? (process.env.HERDR_SCHEDULER_HOME || undefined)
  const outDir = opt['plugin-out'] ?? join(TOOL_ROOT, 'plugin')
  const node = process.execPath
  if ([TOOL_ROOT, node, homeDir ?? ''].some(p => p.includes("'"))) throw new Error("paths containing ' are not supported")
  const done = []
  mkdirSync(outDir, { recursive: true })
  writeFileSync(join(outDir, 'herdr-plugin.toml'), manifest({ id, node, homeDir }), 'utf8')
  done.push(`wrote ${join(outDir, 'herdr-plugin.toml')}`)
  if (homeDir) process.env.HERDR_SCHEDULER_HOME = homeDir
  mkdirSync(home(), { recursive: true })
  // tool_root: the installed Claude Code plugin is a cached copy and finds the real code here.
  // server_socket: the only herdr server allowed to run the scheduler (the plugin registry is global).
  const socket = opt.socket ?? process.env.HERDR_SOCKET_PATH ?? null
  writeJson(join(home(), 'install.json'), { tool_root: TOOL_ROOT, node, server_socket: socket, installed_at: new Date().toISOString() })
  done.push(`wrote ${join(home(), 'install.json')} (owner server ${socket ?? 'any'})`)
  if (opt.shim) {
    const bin = join(homedir(), '.local', 'bin')
    mkdirSync(bin, { recursive: true })
    writeFileSync(join(bin, 'hsched.cmd'), `@echo off\r\n"${node}" "${join(TOOL_ROOT, 'bin', 'hsched.mjs')}" %*\r\n`, 'utf8')
    done.push(`wrote ${join(bin, 'hsched.cmd')}`)
  }
  if (opt.link) {
    await herdr.call(['plugin', 'link', outDir])
    done.push(`linked ${outDir} as ${id}`)
  }
  return { installed: true, id, steps: done }
}
